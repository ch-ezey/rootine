-- Baseline schema for Rootine (PostgreSQL)

CREATE TABLE users (
    user_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid        UUID         NOT NULL UNIQUE,
    name        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP(6),
    last_login  TIMESTAMP(6)
);

CREATE TABLE routine (
    routine_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER       NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    name         VARCHAR(255)  NOT NULL,
    description  VARCHAR(1000),
    detail_level VARCHAR(10)   NOT NULL DEFAULT 'medium'
        CHECK (detail_level IN ('low', 'medium', 'high')),
    is_active    BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMP(6)
);

CREATE INDEX idx_routine_user ON routine (user_id);

-- At most one active routine per user
CREATE UNIQUE INDEX ux_routine_one_active_per_user ON routine (user_id) WHERE is_active;

CREATE TABLE task (
    task_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_id   INTEGER       NOT NULL REFERENCES routine (routine_id) ON DELETE CASCADE,
    title        VARCHAR(150)  NOT NULL,
    description  VARCHAR(1000),
    type         VARCHAR(20)   NOT NULL DEFAULT 'routine'
        CHECK (type IN ('routine', 'one_time', 'event', 'habit')),
    start_time   TIME,
    duration     INTEGER CHECK (duration > 0),
    priority     VARCHAR(10)   NOT NULL DEFAULT 'medium'
        CHECK (priority IN ('low', 'medium', 'high')),
    is_completed BOOLEAN       NOT NULL DEFAULT FALSE,
    position     INTEGER       NOT NULL DEFAULT 0,
    created_at   TIMESTAMP(6)
);

CREATE INDEX idx_task_routine_position ON task (routine_id, position);
